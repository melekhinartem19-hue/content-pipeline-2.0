// Демо сборки PDF без Telegram и без claude -p: пример структуры → render/out/demo.pdf (T13).
//
// Зачем отдельно от смоука: смоук проверяет утверждениями и подчищает за собой, а сюда приходят,
// когда нужно ПОСМОТРЕТЬ ГЛАЗАМИ — после правки вёрстки в templates/pdf.html, после заполнения
// brand-brain/08-visual-style.md или после деплоя на VPS (там ещё и шрифты с кириллицей).
//
//   cd render && npm install && npm run demo:pdf
//   node render/demo-pdf.mjs путь/к/структуре.txt
//
// Второй вариант удобен, когда Презентатор уже ответил в топике: скопировал его текст в файл —
// и увидел готовый документ, не гоняя весь конвейер.

import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderPdf } from './index.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Встроенный пример: все три роли страниц (обложка → раскрытие → финал с CTA). */
const SAMPLE = `Лид-магнит по теме «контент-план», 5 страниц: как за час собрать план на месяц.

=== СТРАНИЦА 1 ===
Заголовок: Контент-план на месяц за один час
Текст: Пошаговый разбор для тех, кто каждый день начинает с вопроса «а что сегодня постить»
Визуал: крупная типографика, акцентная плашка снизу

=== СТРАНИЦА 2 ===
Заголовок: Шаг 1. Соберите темы в одном месте
Текст: Заведите список и складывайте туда всё: вопросы клиентов, возражения на созвонах, посты конкурентов, которые зацепили. Задача шага — не придумать темы, а перестать их терять. За неделю такой список набирает 20–30 строк, и «что постить» превращается в «что выбрать».
Визуал: сетка пунктов, чек-лист

=== СТРАНИЦА 3 ===
Заголовок: Шаг 2. Разложите темы по трём полкам
Текст: Полка «польза» — то, что человек может применить сегодня. Полка «доверие» — кейсы, процесс, люди за кадром. Полка «продажа» — оффер и приглашение к следующему шагу. Держите пропорцию примерно 3:2:1 — тогда лента не превращается ни в вебинар, ни в витрину.
Визуал: три столбца сравнения

=== СТРАНИЦА 4 ===
Заголовок: Шаг 3. Разнесите по датам с запасом
Текст: Ставьте не больше четырёх публикаций в неделю и оставляйте один свободный слот: он уйдёт под новость, отзыв или ответ на вопрос из комментариев. План без свободного места ломается на первой же нештатной неделе.
Визуал: волна, плавный поток

=== СТРАНИЦА 5 ===
Заголовок: Заберите шаблон плана
Текст: Напишите слово «план» в личные сообщения — пришлём таблицу с тремя полками и готовыми датами.
Визуал: мягкое тёплое пятно, акцент по центру`;

const fileArg = process.argv[2];
const content = fileArg ? await fsp.readFile(fileArg, 'utf8') : SAMPLE;
const outFile = path.join(__dirname, 'out', 'demo.pdf');
const brandBrainDir = path.join(__dirname, '..', 'brand-brain');

console.log(fileArg ? `Структура из файла: ${fileArg}` : 'Структура: встроенный пример');
const res = await renderPdf({ content, outFile, brandBrainDir, title: 'Демо лид-магнита' });

if (!res.ok) {
  console.error(`\n⚠️  Сборка PDF не удалась: ${res.error}`);
  process.exit(1);
}

console.log(`\n✅ ${res.note}`);
console.log(`Файл: ${res.file}`);
console.log('\nОткрой его и посмотри глазами — вёрстка проверяется только так.');
