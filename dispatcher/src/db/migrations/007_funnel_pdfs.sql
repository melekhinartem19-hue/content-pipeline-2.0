-- 007_funnel_pdfs — собранные PDF-лид-магниты инста-воронки (T13).
--
-- По строке на ТЕМУ, а не на прогон: тем ровно три (см. manychat/funnel.json), и воронке в
-- ManyChat нужна ровно одна актуальная ссылка на каждую. Пересборка темы перезаписывает строку —
-- ключ темы и есть первичный ключ. Так ссылка, уже разосланная людям, остаётся той же самой
-- (файл в статике перезаписывается), а «какой PDF сейчас живой» не приходится вычислять.
--
-- Почему ссылку храним, а не собираем на лету: адрес зависит от PUBLIC_BASE_URL, который живёт
-- в .env конкретной установки. Настройку могут поменять — а T14 должен отдавать ту ссылку,
-- по которой файл реально выложен.

CREATE TABLE IF NOT EXISTS funnel_pdfs (
  key        TEXT PRIMARY KEY,           -- ключ темы из manychat/funnel.json (он же имя файла)
  title      TEXT NOT NULL,              -- название темы: уходит в текст ответа воронки
  file       TEXT NOT NULL,              -- локальный путь к собранному PDF
  url        TEXT,                       -- публичная ссылка (Nginx). NULL = статика ещё не настроена
  pages      INTEGER,                    -- сколько страниц собралось
  built_at   TEXT NOT NULL DEFAULT (datetime('now')),
  meta       TEXT                        -- JSON: заметки сборки (тема brand-brain, обрезка и т.п.)
);
