-- 011_app_state — маленькая память диспетчера «между перезапусками» (T16).
--
-- ЗАЧЕМ. Расписаниям нужно помнить, что они уже отработали. У сбора трендов такая память есть
-- естественная (прогон записан в trend_runs и виден по дате), а у еженедельного отчёта Аналитика
-- следа нет: отчёт уходит сообщением в топик и в базе ничего не оставляет. Держать «когда был
-- последний отчёт» в памяти процесса нельзя — перезапуск диспетчера прислал бы отчёт повторно.
--
-- Нарочно ключ-значение, а не колонки: сюда попадают редкие служебные отметки планировщиков,
-- и заводить миграцию на каждую такую отметку — лишний шум.
--
-- ⚠ Диалект: datetime('now') → now() при переезде на Postgres. См. specs/db.md.

CREATE TABLE IF NOT EXISTS app_state (
  key        TEXT PRIMARY KEY,
  value      TEXT,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
