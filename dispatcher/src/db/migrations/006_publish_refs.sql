-- 006_publish_refs — id поста на площадке, где он больше не помещается в число (T11/T12).
--
-- В T08 хватало published_message_id: id сообщения Telegram — обычное небольшое целое.
-- У Instagram и Threads id поста — 17–18-значное число, которое уже НЕ помещается в
-- безопасный диапазон целых JavaScript (2^53): при чтении оно тихо теряло бы последние цифры,
-- и по такому id пост потом не найти. Поэтому ссылка на опубликованное хранится строкой.
--
-- published_message_id остаётся как есть (Telegram), published_ref заполняется всегда — это
-- единая «где искать пост» для всех трёх площадок.

ALTER TABLE approval_queue ADD COLUMN published_ref TEXT;
