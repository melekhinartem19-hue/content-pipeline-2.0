// Что вообще попадает в очередь согласования (T07).
//
// Через `claude -p` проходят разные ответы агентов, и далеко не каждый — публикуемый контент:
// план Продюсера, отчёт по трендам и предпубликационная проверка Издателя согласовывать нечего.
// Поэтому решает не «кто ответил», а `kind` из META-конверта: есть площадка → в очередь.
//
// Соответствие kind → площадка задаёт и ТРИ РАЗДЕЛЬНЫХ СОГЛАСОВАНИЯ из CLAUDE.md: форматы TG,
// IG и Threads разные, поэтому элемент очереди всегда привязан ровно к одной площадке.

const KIND_PLATFORM = {
  tg_post: 'tg', // Сценарист: пост в Telegram
  carousel_spec: 'ig', // Дизайнер: карусель (рендер — T10)
  cover_spec: 'ig', // Дизайнер: обложка
  reels_script: 'ig', // Сценарист: сценарий Reels (монтаж — T15)
  reels_video: 'ig', // готовый ролик с ноута клиента (T15): в meta.video_url — публичная ссылка
  threads_post: 'threads', // текст под Threads (публикация — T11)
};

// Сознательно НЕ согласовываем:
//   producer_plan  — раздача задач, не контент;
//   trend_report   — сырьё для тем;
//   publish_check  — это сама проверка Издателя;
//   pdf_spec       — лид-магнит инста-воронки идёт своей веткой (T13), не через ленту публикаций.

/** Площадка для этого вида контента или null, если согласовывать нечего. */
export function platformForKind(kind) {
  return KIND_PLATFORM[String(kind || '')] || null;
}

/** Стоит ли класть ответ агента в очередь согласования. */
export function isPublishable(meta) {
  return platformForKind(meta?.kind) !== null;
}
