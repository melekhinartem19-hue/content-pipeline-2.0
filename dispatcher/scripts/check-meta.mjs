// Предполётная проверка публикации из консоли VPS: npm run check:meta
//
// Первая команда, которую надо запустить, когда приехали креды клиента. Она НИЧЕГО НЕ ПУБЛИКУЕТ:
// только читает Graph API и один раз проверяет, видна ли публичная статика снаружи. Поэтому её
// можно гонять сколько угодно раз, правя .env между прогонами.
//
// Порядок на го-лайве:
//   1) вписать креды в dispatcher/.env
//   2) npm run check:meta        ← пока не зелено, публиковать бессмысленно
//   3) PUBLISH_DRY_RUN=1 и «Одобрить» — посмотреть план вызовов
//   4) снять флаг, перезапустить сервис, опубликовать по-настоящему
//
// Код возврата: 0 — обе площадки готовы, 1 — есть блокирующие проблемы (удобно для скриптов).

import { config } from '../src/config.js';
import { preflight, renderPreflight } from '../src/publish/preflight.js';

const res = await preflight({ config });
console.log(renderPreflight(res));

if (config.publishDryRun) {
  console.log('\nℹ️ PUBLISH_DRY_RUN=1 — на саму проверку он не влияет (она и так ничего не публикует),');
  console.log('   но реальные публикации при нём тоже не уйдут. Перед боевым запуском флаг снять.');
}

process.exit(res.ig && res.threads ? 0 : 1);
